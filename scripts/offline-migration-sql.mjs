// Generates canonical Prisma migration SQL (identical to `prisma migrate dev --create-only`)
// using Prisma's bundled WASM schema engine, so no engine binary download is required.
//
//   node scripts/offline-migration-sql.mjs <migration_name>                    (initial migration from an empty database)
//   node scripts/offline-migration-sql.mjs <migration_name> --from <old.prisma> (delta between an old schema file and the current one)
//
// Writes the SQL to a new folder under prisma/migrations.
// This is an OPTIONAL helper. The normal flow is `npm run db:setup`.
import fs from "node:fs";
import path from "node:path";
import "dotenv/config";
import { PrismaPg } from "@prisma/adapter-pg";
import { bindMigrationAwareSqlAdapterFactory } from "@prisma/driver-adapter-utils";
import { SchemaEngine } from "@prisma/schema-engine-wasm";

const name = process.argv[2];
if (!name) { console.error("usage: node scripts/offline-migration-sql.mjs <migration_name>"); process.exit(1); }

const schemaPath = "prisma/schema.prisma";
const schema = fs.readFileSync(schemaPath, "utf8");
const migrationsDir = "prisma/migrations";
const existing = fs.existsSync(migrationsDir)
  ? fs.readdirSync(migrationsDir).filter((d) => fs.statSync(path.join(migrationsDir, d)).isDirectory()).sort()
  : [];
const fromIdx = process.argv.indexOf("--from");
const fromPath = fromIdx > 0 ? process.argv[fromIdx + 1] : null;
if (existing.length > 0 && !fromPath) {
  console.error("Existing migrations found: pass --from <old schema file> to generate a delta migration.");
  process.exit(1);
}

const url = process.env.DATABASE_URL;
if (!url) { console.error("DATABASE_URL is not set (this developer helper needs a scratch database)."); process.exit(1); }
const adapter = bindMigrationAwareSqlAdapterFactory(new PrismaPg({ connectionString: url }));
const engine = await SchemaEngine.new({ datamodels: [[schemaPath, schema]] }, () => {}, adapter);
const res = await engine.diff({
  from: fromPath ? { tag: "schemaDatamodel", files: [{ path: "old.prisma", content: fs.readFileSync(fromPath, "utf8") }] } : { tag: "empty" },
  to: { tag: "schemaDatamodel", files: [{ path: schemaPath, content: schema }] },
  script: true, exitCode: null, shadowDatabaseUrl: null,
  filters: { externalTables: [], externalEnums: [] },
});
const last = existing.length ? Number(existing[existing.length - 1].split("_")[0]) : 20261030000000;
const stamp = String(last + 1);
const dir = path.join(migrationsDir, `${stamp}_${name}`);
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, "migration.sql"), res.stdout);
fs.writeFileSync(path.join(migrationsDir, "migration_lock.toml"),
  '# Please do not edit this file manually\nprovider = "postgresql"\n');
console.log(`wrote ${dir}/migration.sql (${res.stdout.split("\n").length} lines)`);
process.exit(0);
